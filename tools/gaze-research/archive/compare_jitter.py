#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""
compare_jitter.py — 指尖与虹膜的抖动谁更关键（正确口径）

背景
----
现场数据：
    指尖  最小值 0.001763（≈3.4px）   实际用时 0.068693（≈20 倍）
    虹膜  最小值 0.000657（≈1.3px）   平均误差 400px

直觉上"指尖 3.4px 远好于虹膜 400px"，但这个对比口径不对 ——
两者都是【归一化坐标】，比较前必须除以各自的【活动范围】，
因为同样的抖动，活动范围越大，换算到屏幕上的可分辨精度就越高。

正确口径： 相对抖动 = 抖动的归一化值 / 活动范围的归一化值
它等价于"在屏幕上的有效精度占比"。

用法： python tools/compare_jitter.py
"""
import sys

for _s in ('stdout', 'stderr'):
    try:
        getattr(sys, _s).reconfigure(encoding='utf-8', errors='replace')
    except Exception:
        pass


def main():
    SCREEN_DIAG = 1981.0      # 本项目视口对角线（CSS px，实测）

    print('=' * 78)
    print('正确口径：相对抖动 = 归一化抖动 / 归一化活动范围')
    print('=' * 78)
    print('  %-22s %-14s %-14s %-12s %s'
          % ('方案', '归一化抖动', '归一化范围', '相对抖动', '换算屏幕像素'))
    print('  ' + '-' * 74)

    cases = [
        # 名称,                     抖动,        活动范围,     来源
        ('虹膜（视线）',            0.000657,    0.0153,      '实测 measure_snr.py'),
        ('指尖（悬空，最小值）',     0.001763,    0.312,       '实测 hand-test'),
        ('指尖（悬空，实际用时）',   0.068693,    0.312,       '实测 HUD'),
        ('指尖（靠桌，估计）',       0.000800,    0.10,        '推测：靠桌更稳但范围更小'),
    ]
    for name, jit, rng, src in cases:
        rel = jit / rng
        px = rel * SCREEN_DIAG
        print('  %-22s %-14.6f %-14.4f %-12.5f %.1f px'
              % (name, jit, rng, rel, px))

    print('\n' + '=' * 78)
    print('结论')
    print('=' * 78)
    print('  1. 虹膜的【最小值】很美（0.000657），但它的活动范围只有 0.0153 ——')
    print('     相对抖动 4.3%，换算屏幕 85px。信号本身就在噪声量级。')
    print()
    print('  2. 指尖悬空时"实际用时"抖动 0.0687，活动范围 0.312 ——')
    print('     相对抖动 22%，换算屏幕 436px。看起来更差，但这是【悬空】的情况。')
    print()
    print('  3. 指尖悬空时的【最小值】抖动 0.001763，相对抖动 0.56% ——')
    print('     换算屏幕仅 11px。也就是说：手指能稳到 11px 量级，')
    print('     只是人无法持续保持，平均值被拉高了 20 倍。')
    print()
    print('  4. 关键推论：对指尖方案，瓶颈【不是】抖动下限，而是')
    print('     "能否长期保持稳定姿态"。而这个问题可以靠交互设计解决：')
    print('        · 时间积分已经做了（200ms 窗口中位数）')
    print('        · 可以再引入"等待稳定再计时"的 dwell —— 抖的时候不计时，')
    print('          稳住了才开始累积。这样抖动只影响速度，不影响正确性。')
    print()
    print('  5. 所以"手腕靠桌面"不是必需品。它能让抖动从 0.069 降到 0.03 左右，')
    print('     但代价是手落出摄像头视野（摄像头在显示器顶部朝下看）。')
    print('     保持悬空 + 依赖时间积分，是更实际的组合。')
    return 0


if __name__ == '__main__':
    sys.exit(main())
