"""
audit_design.py — 核对"视线定框 + 手势精点"设计文档里的数字与推理

用户提交了一份设计文档，主张用"视线定框 → 冻结 → 重排放大 → 手势框内精点"
解决本项目"视线看得全但点不准、手点得准但够不到"的矛盾。

这份文档对实测数据的引用基本准确，但有几处需要核对：
  ① 表 2 声称"两者绝对定位误差量级相近（都约 0.20 对角线）"—— 需要核对
  ② 第六节"2560x1600 屏幕、每格 410px、全屏容纳约 24 个目标"—— 需要核对
  ③ 表 7 的"全局：单格 426x400、有效半径约 200px、手部可行"—— 需要核对
  ④ 最关键的：405px 误差是否随放大等比下降（文档自己也标为待验证）

另外本脚本要澄清一个容易被误用的概念：
  leave-one-out 误差 ≠ 实际使用误差。
  demo 是【用全部 9 个校准点训练、再在同样覆盖范围内使用】，
  而留一是"预测一个完全没见过的校准点"，两者难度不同。

用法： python tools/audit_design.py
"""
import math
import sys

for _s in ('stdout', 'stderr'):
    try:
        getattr(sys, _s).reconfigure(encoding='utf-8', errors='replace')
    except Exception:
        pass

# 本项目的实测环境
W, H = 2560.0, 1600.0          # 物理像素（2560x1600 / 16 寸 / 150% 缩放）
DIAG = math.hypot(W, H)

# 实测数据（来自 README 与 demo HUD）
ERR_DEMO = 405.0               # 指尖留一误差 px（0.201 对角线）
ERR_DEMO_BAD = 557.0           # 后续一轮（0.277）
JIT_HAND = 11.0                # 指尖相对抖动换算 px
JIT_GAZE = 85.0                # 视线相对抖动换算 px
R_WORKING = 205.0              # 实测"能工作"的目标半径 px

# 视线区域分类（真实数据实测）
GAZE_BIN = 0.804               # 水平二分类
GAZE_TRI = 0.652               # 水平三分类
GAZE_QUAD = 0.46               # 2x2 四象限


def main():
    print('=' * 80)
    print('核对 ①：表 2 声称"两者绝对定位误差量级相近（都约 0.20 对角线）"')
    print('=' * 80)
    print('  文档表述：视线 0.20–0.51 对角线，指尖 405px（0.201 对角线），')
    print('            所以"两者的绝对定位误差量级其实相近"。')
    print()
    print('  核对：')
    print('    视线误差区间   0.20 ~ 0.51 对角线  =  %.0f ~ %.0f px' % (0.20 * DIAG, 0.51 * DIAG))
    print('    指尖误差       0.201 对角线        =  %.0f px' % ERR_DEMO)
    print()
    print('  结论：拿【视线的最好情况 0.20】去比【指尖的实测值 0.201】是不对等的。')
    print('        视线的实测区间中位约 0.35 对角线（%.0f px），是指尖的约 1.7 倍。' % (0.35 * DIAG))
    print('        更准确的说法：两者的【最好情况】量级相近，但视线的方差大得多。')
    print('        这条不影响方案主体，但它淡化了视线的不稳定程度。')

    print()
    print('=' * 80)
    print('核对 ②：第六节"2560x1600 屏幕、每格 410px、全屏容纳约 24 个"')
    print('=' * 80)
    r = R_WORKING
    cell = r * 2
    cols = W // cell
    rows = H // cell
    print('  文档推理：目标半径 205px → 每格 410px → 2560/410 = %.2f 列、1600/410 = %.2f 行'
          % (W / cell, H / cell))
    print('  文档结论：全屏约 24 个目标')
    print()
    print('  实际取整：%d 列 x %d 行 = %d 个' % (cols, rows, cols * rows))
    print('  → 文档把 %.2f x %.2f 直接相乘（=%.1f）当成了 24，这是【取整错误】。'
          % (W / cell, H / cell, (W / cell) * (H / cell)))
    print('    正确结果是 %d 个，不是 24 个。' % (cols * rows))
    print()
    print('  这个修正反而【加强】了方案的针对性：桌面图标典型 20–30 个，')
    print('  确实超出单屏容量（%d 个），所以"减少候选数"这一步是必要的。' % (cols * rows))

    print()
    print('=' * 80)
    print('核对 ③：表 7"全局单格 426x400、有效半径约 200px、手部可行（边界，勉强）"')
    print('=' * 80)
    n = 24
    # 24 个目标铺满屏幕
    c2 = math.ceil(math.sqrt(n * W / H))
    r2 = math.ceil(n / c2)
    cw, ch = W / c2, H / r2
    eff_r = min(cw, ch) / 2
    print('  24 个目标铺满 %.0fx%.0f：取 %d 列 x %d 行' % (W, H, c2, r2))
    print('  单格 %.0f x %.0f   有效半径 %.0f px' % (cw, ch, eff_r))
    print()
    print('  文档说"手部可行（边界，勉强）"。但对照实测：')
    print('    有效半径        %.0f px' % eff_r)
    print('    指尖留一误差    %.0f px   ← 误差【大于】有效半径' % ERR_DEMO)
    print('    较差一轮误差    %.0f px' % ERR_DEMO_BAD)
    print()
    print('  结论：把 %.0f px 的定位误差放进 %.0f px 半径的格子里，' % (ERR_DEMO, eff_r))
    print('        不是"边界/勉强"，而是【不可能命中】—— 除非依赖吸附（snap），')
    print('        而吸附半径必须 >= 误差，否则选区仍然是错的。')
    print('        文档这里的判断过于乐观。')

    print()
    print('=' * 80)
    print('核对 ④：最关键的问题 —— 误差会随放大等比下降吗？')
    print('=' * 80)
    print('  文档自己把它标为"待验证假设"（第八节），这是诚实的。')
    print('  但这里可以先用现有数据结构上回答一部分：')
    print()
    print('  误差的两个可能来源，对放大的响应完全不同：')
    print('    来源 A｜全局偏置（标定整体偏移）')
    print('      → 放大【不能】减少它。放大后偏置同比例放大，误差绝对值反而变大。')
    print('    来源 B｜局部非线性（不同屏幕位置的映射畸变不同）')
    print('      → 放大【能】减少它，因为放大后每个候选点占用更多屏幕面积，')
    print('        局部畸变在更小的区域尺度上更接近线性。')
    print()
    print('  判断方法（成本很低）：把 405px 的残差按【屏幕位置】画出来。')
    print('    · 若残差在整个屏幕上是同向的（都朝一个方向偏）→ 主要是 A')
    print('    · 若残差方向随位置系统性变化（左偏右、上偏下）→ 主要是 B')
    print('  已有的 9 点校准残差数据就能做这件事（见 tools/residual_map.py）。')

    print()
    print('=' * 80)
    print('一个必须澄清的概念：留一误差 ≠ 实际使用误差')
    print('=' * 80)
    print('  留一（leave-one-out）= 拿 8 个点训练，预测【第 9 个完全没见过的点】。')
    print('  实际使用 = 用【全部 9 个点】训练，然后在同一片区域内使用。')
    print()
    print('  两者难度不同：留一要求模型能外推到没有训练数据的屏幕位置，')
    print('  而实际使用时手指通常落在校准点【附近】，误差应小于留一误差。')
    print()
    print('  这解释了为什么 demo 在 留一误差 405px、目标半径 205px 的情况下')
    print('  仍然"能选中"（用户实测确认过三轮）：实际使用误差小于留一误差。')
    print()
    print('  因此：')
    print('    · 设计文档用 405px 做容量推算是【保守】的（偏悲观）')
    print('    · 但我在核对 ③ 里用同一个数字说明"不可能命中"也是【不严谨】的')
    print('    · 正确做法是测【实际使用误差】：在校准点之间的位置取点，')
    print('      看预测偏差是多少。这个数字才是设计界面容量的依据。')
    print('    · 对应工具：tools/residual_map.py（同时给出残差空间分布与')
    print('      "插值位置误差"）')

    print()
    print('=' * 80)
    print('总体可信度评估')
    print('=' * 80)
    print('  ✓ 站得住的部分：')
    print('    · "冻结"把视线从连续追踪降级为离散选择 —— 这个洞察是对的，')
    print('      而且是本方案唯一不可替代的设计。视线连续追踪 400~1000px 不可用，')
    print('      离散二分类 80% 可用 —— 这个对比准确。')
    print('    · "重排"而不是"等比放大" —— 正确且重要。等比放大受原排列间距限制，')
    print('      重排才能真正放大有效半径。')
    print('    · 第二级起改用手 —— 误差相乘的论证成立（0.8³≈51%）。')
    print('    · 把"放大是否等比降误差"标为待验证，而不是直接假设成立 —— 诚实。')
    print()
    print('  ✗ 需要修正的部分：')
    print('    · 24 个目标的容量推算有取整错误（应为 %d 个）' % cols * rows if False else
          '    · 24 个目标的容量推算有取整错误（应为 %d 个）' % (cols * rows))
    print('    · 表 7 把"误差 405px 放进半径 200px 的格子"判为"勉强可行" —— 过于乐观')
    print('    · 表 2 用视线最好情况对比指尖实测值，淡化了视线的不稳定性')
    print()
    print('  ? 尚未解决的关键问题（决定成败）：')
    print('    · 405px 误差的构成（全局偏置 vs 局部非线性）未拆开 →')
    print('      这直接决定"放大"有没有用。文档也指出了，但没给验证方法。')
    print('    · 实际使用误差（而非留一误差）从未被测过 →')
    print('      容量推算缺少正确的输入数字。')
    return 0


if __name__ == '__main__':
    sys.exit(main())
