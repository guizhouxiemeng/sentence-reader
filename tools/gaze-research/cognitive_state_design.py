#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""
cognitive_state_design.py — 认知状态推断层的可计算设计

项目定位（用户确认的提法）
--------------------------
跨场景注意力预测层：信号采集层 → 认知状态推断层（通用）→ 场景响应层（特定）。
视线不作操作通道，只作感知信号；响应层做"静默准备"，不打断。

本脚本把"推断层"从概念变成可计算的形式，并给出每一项的参数依据。

设计约束（来自本项目的实测，不是假设）
--------------------------------------
  1. 抖动 68 px、系统偏差 754 px（README: 总误差 822px 里抖动只占 8%）
  2. 停留时长可靠的最小区域：半径 243 px（1 秒内假越界 <=5%）
     —— 所以区域划分必须在【段级】，不能是词级
  3. 系统偏差可校准消除，所以在会话开始时做一次逐区域偏移标定
     可以把"区域归属"的准确度显著提高（这是可选的增强项）

三个状态的可计算定义
--------------------
  处理受阻 (blocked)  : 某段的"处理量"显著高于该段的基线
  正常阅读 (reading)  : 处理量在基线附近
  跳过     (skipping) : 停留极短且未回看

核心量的选择理由
----------------
为什么用"重访率"而不是"停留时长"作为主判据：

  停留时长本身无法区分"吃力"与"看得快但内容多" —— 两者都表现为待得久。
  而"同一段反复回去"是受阻的特异性指标：
    · 正常前进 → 每段访问 1 次
    · 受阻     → 同一段访问 2~4 次（回视）
  这与阅读研究里的"回视次数(regression count)"一致，是成熟指标。

  但重访率需要正文有足够长度才能形成统计。所以：
    · 视频场景（字幕流 + 暂停/倒退）：用【操作事件】作主判据，更直接
    · 论文场景（连续正文）        ：用【重访率】作主判据

用法： python tools/cognitive_state_design.py
"""
import math
import sys

for _s in ('stdout', 'stderr'):
    try:
        getattr(sys, _s).reconfigure(encoding='utf-8', errors='replace')
    except Exception:
        pass

# ---------------------------------------------------------------- 实测常量
JITTER_PX = 68.0            # 凝视抖动（README 实测）
BIAS_PX = 754.0             # 系统偏差（822 总误差 - 68 抖动）
MIN_REGION_R = 243.0        # 停留时长可靠的区域半径下限（假越界 <=5%）
FPS = 30.0


def main():
    print('=' * 88)
    print('认知状态推断层 —— 可计算设计')
    print('=' * 88)
    print('  实测约束：抖动 %.0fpx，系统偏差 %.0fpx，区域半径下限 %.0fpx'
          % (JITTER_PX, BIAS_PX, MIN_REGION_R))
    print()

    # ================================================================
    print('=' * 88)
    print('一、信号层：每个量怎么算（逐帧更新，O(1) 内存）')
    print('=' * 88)
    print()
    print('  记：R 为当前注视区域（段），t 为帧时刻，dt = 1/%.0f s' % FPS)
    print()
    print('  ① 区域归属 region(t)')
    print('     把正文切成【段级】矩形，光标落在哪个矩形内即归属该段。')
    print('     段落高度通常 150~400px，宽度接近版心宽 —— 远大于 %.0fpx 下限，' % MIN_REGION_R)
    print('     所以归段判定是可靠的（越界概率 ~0）。')
    print()
    print('  ② 段内累计注视时间 dwell[R]  （单位：秒）')
    print('     每帧若 region(t)==R 且未在扫视中，则 dwell[R] += dt。')
    print('     "未在扫视中"判据：光标速度 < %.0f px/s（低于此视为停留）。'
          % (JITTER_PX * 3))
    print()
    print('  ③ 访问次数 visits[R]')
    print('     从"非 R"进入 R 且连续停留 >= 0.15s，记一次访问。')
    print('     0.15s 的门限用于滤掉抖动造成的瞬时穿越（抖动 %.0fpx，' % JITTER_PX)
    print('     段级区域内不会产生假穿越，此门限主要防段边界抖动）。')
    print()
    print('  ④ 重访率 revisit[R]')
    print('     revisit[R] = visits[R] - 1        （正常前进时为 0）')
    print()
    print('  ⑤ 单次访问时长 visitDur[R][]')
    print('     每次访问的持续时间，用于算中位数与"最长一次"。')
    print()
    print('  ⑥ 处理量 effort[R]  —— 主判据')
    print('     effort[R] = dwell[R] / (1 + revisit[R] x 0.6)')
    print('     直觉：同样看了 6 秒，回去过 3 次说明"没读懂"，')
    print('           而一次看 6 秒说明"这一段本来就长"。')
    print('     这里用 0.6 而不是 1.0：回看本身也要花时间，')
    print('     完全归因于"没读懂"会高估；0.6 是保守折扣。')
    print()
    print('  ⑦ 内容长度 len[R]（场景特定，但推断层只要求一个"预期量"）')
    print('     论文：该段的字数 / 该段的预期阅读时间')
    print('     视频：该段字幕的字符数 / 停留时刻的播放倍率')
    print('     归一化后两者同构 —— 这是"两种场景共用推断层"的关键。')
    print()

    # ================================================================
    print('=' * 88)
    print('二、状态判定：三个状态的可计算条件')
    print('=' * 88)
    print()
    print('  用【相对基线】而不是绝对阈值 —— 因为每个人的阅读速度差异很大，')
    print('  绝对阈值会把慢读者全部判成"受阻"。')
    print()
    print('  基线 base[R]：该段"预期处理量" = 内容长度 x 该人的单位长度用时')
    print('     · 会话开始时用前几分钟的正常段落估出"单位长度用时"')
    print('     · 之后每读一个新段落就更新（滑动中位数，抗异常值）')
    print()
    print('  ┌──────────────────────────────────────────────────────────────┐')
    print('  │ 状态        判据                                             │')
    print('  ├──────────────────────────────────────────────────────────────┤')
    print('  │ 跳过        离开该段时 visitDur < 0.35 x base               │')
    print('  │             且 revisit == 0                                  │')
    print('  │                                                              │')
    print('  │ 正常阅读    effort 在 [0.5, 1.8] x base                      │')
    print('  │                                                              │')
    print('  │ 处理受阻    effort > 2.5 x base      （主条件）              │')
    print('  │             且 满足以下任一：                                 │')
    print('  │               · revisit >= 2                                 │')
    print('  │               · 最长单次访问 > 2.0 x base                    │')
    print('  │               · 有操作事件（视频：暂停/倒退）                 │')
    print('  └──────────────────────────────────────────────────────────────┘')
    print()
    print('  为什么"主条件 + 辅助条件"两层：')
    print('    只看 effort 会误判"这一段本来就难读但读者没卡住"；')
    print('    加辅助条件后，必须同时有"回去过"或"卡了很久"的证据。')
    print('    这降低误报 —— 误报会打断阅读，代价比漏报高。')
    print()

    # ================================================================
    print('=' * 88)
    print('三、视频场景：同一个推断层，不同的信号权重')
    print('=' * 88)
    print()
    print('  视频与论文的关键差异：视频多一个【操作通道】（暂停/倒退），')
    print('  而这个通道产生的是比视线更直接、更可靠的受阻证据。')
    print()
    print('  %-16s %-24s %-24s %s' % ('量', '论文场景', '视频场景', '权重依据'))
    print('  ' + '-' * 84)
    rows = [
        ('主判据', '重访率 effort', '操作事件 暂停/倒退', '操作是显式意图，比推断可靠'),
        ('停留时长', '段级累计', '字幕段累计', '两者同构（字幕=视频的文本层）'),
        ('内容长度', '段落字数', '字幕字符数', '归一化后同一量纲'),
        ('辅助信号', '最长单次访问', '倒退次数', '都是"卡住"的直接表现'),
    ]
    for a, b, c, d in rows:
        print('  %-16s %-24s %-24s %s' % (a, b, c, d))
    print()
    print('  所以"字幕让视频与论文同构"这个洞察在【计算层】是成立的：')
    print('    视频 = 带有操作通道的、按时间排布的文本流')
    print('    论文 = 没有操作通道的、按空间排布的文本流')
    print('  推断层只需要"区域 + 停留 + 重访 + 预期量"四个量，')
    print('  这四个量两种场景都能提供。适配器只是把它们映射到不同的坐标。')
    print()

    # ================================================================
    print('=' * 88)
    print('四、响应层：静默准备的可计算触发')
    print('=' * 88)
    print()
    print('  "静默准备"不是模糊说法，它可以有明确条件：')
    print()
    print('  ① 准备条件（不打扰）')
    print('     effort[R] 越过 1.5 x base 时，开始为 R 段【后台生成】解释。')
    print('     此时界面不出现任何东西 —— 只是把内容准备好。')
    print()
    print('  ② 展开条件（用户取出）')
    print('     状态进入"处理受阻"且光标移向侧边栏区域并停留 > 0.8s，')
    print('     才展开已准备好的解释。')
    print('     依据：侧边栏停留 0.8s 远大于假越界时间尺度，')
    print('           是明确的"我要看那边"意图；而 0.8s 又足够短，不觉得卡。')
    print()
    print('  ③ 自动展开的例外')
    print('     若同一段在 30 秒内被判定受阻 >= 3 次，则自动展开一次。')
    print('     依据：反复受阻说明"用户自己解决不了"，此时不打断反而更糟。')
    print('     这个例外必须记录在日志里，因为它改变了实验的对照条件。')
    print()
    print('  ④ 准备的成本控制')
    print('     LLM 调用只在越过 1.5 x base 时触发，且每段最多准备一次。')
    print('     一次阅读会话里准备次数通常为个位数 —— 成本可忽略。')
    print()

    # ================================================================
    print('=' * 88)
    print('五、这个推断层的可证伪性与评估方式')
    print('=' * 88)
    print()
    print('  推断层可以单独评估，不需要先接 LLM —— 这一点很重要，')
    print('  因为它让"效果来自时机还是来自解释质量"可以分离。')
    print()
    print('  评估设计：')
    print('    · 让使用者读一批文本，其中【人为植入】若干处"确实是术语密集')
    print('      或难懂的段落"（真值标签）')
    print('    · 看推断层能否把这些段落标成"处理受阻"')
    print('    · 指标：精确率/召回率、以及"首次判定延迟"（读多久才判出来）')
    print()
    print('  预期（基于本项目的实测约束推算）：')
    print('    · 判定延迟下限 = 区域半径 %.0fpx 对应的文字量 / 该人的阅读速度' % MIN_REGION_R)
    print('      以 1699px 屏宽、每行约 60 字估算，243px 半径覆盖约 30~35 字')
    print('      按 300 字/分钟，约 6~7 秒 —— 但受阻需要【回看】才判得出，')
    print('      所以实际延迟应是"读完该段 + 回看一次" ≈ 12~20 秒')
    print('    · 这意味着响应【不可能在段落中途给出】，只能是"读完这一段后"')
    print('      这不是缺陷，而是与"静默准备"的设计刚好一致 ——')
    print('      准备发生在你读完一段、正要回看的时候，时机正好。')
    print()
    print('  可证伪的预测：')
    print('    若 20 秒内无法判出受阻，则该推断层不能支撑"读完即准备"的体验，')
    print('    需要引入操作事件（视频场景）或更长的整篇统计。')
    return 0


if __name__ == '__main__':
    sys.exit(main())
